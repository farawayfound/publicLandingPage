'use strict';
/* The dot-matrix world map: encoding for the browser and the static locator drawn at build time.
 *
 * assets/data/world-dots.json is a list of land points on an offset-row grid (step 1.6 degrees; odd rows are shifted
 * by half a step). Instead of shipping 5,900 [lon,lat] pairs (or a 48 KB inline SVG path) the build run-length
 * encodes each latitude row once into assets/data/world-dots.js (about 5 KB), which the landing page, the story
 * index and the minimap share:
 *
 *   window.FF_WORLD = { step: 1.6, rows: [[lat, [[firstColumn, count], ...]], ...] }
 *
 * A column is one half step (0.8 degrees) counted from longitude -180, and consecutive dots in a run are two
 * columns apart. Decoding (assets/js/ff-map.js):  lon = -180 + (firstColumn + 2*k) * (step / 2)
 */
const fs = require('fs');
const path = require('path');

function readDots(file) {
	const j = JSON.parse(fs.readFileSync(file, 'utf8'));
	if (!j || !Array.isArray(j.dots) || !j.step) throw new Error(`${file}: expected {step, dots:[[lon,lat],...]}`);
	return j;
}

function encodeRle(world) {
	const half = world.step / 2;
	const rows = new Map();
	for (const [lon, lat] of world.dots) {
		const col = (lon + 180) / half;
		if (Math.abs(col - Math.round(col)) > 1e-4) throw new Error(`world-dots: longitude ${lon} is not on the ${half} degree grid`);
		const key = lat.toFixed(2);
		if (!rows.has(key)) rows.set(key, []);
		rows.get(key).push(Math.round(col));
	}
	const out = [];
	for (const key of [...rows.keys()].sort((a, b) => parseFloat(a) - parseFloat(b))) {
		const cols = rows.get(key).sort((a, b) => a - b);
		const runs = [];
		let start = cols[0], n = 1;
		for (let i = 1; i < cols.length; i++) {
			if (cols[i] === cols[i - 1] + 2) n++;
			else { runs.push([start, n]); start = cols[i]; n = 1; }
		}
		runs.push([start, n]);
		out.push([+parseFloat(key).toFixed(2), runs]);
	}
	return { step: world.step, rows: out };
}

function decodeRle(rle) {
	const dots = [];
	const half = rle.step / 2;
	for (const [lat, runs] of rle.rows) for (const [col, n] of runs) for (let k = 0; k < n; k++) dots.push([+(-180 + (col + 2 * k) * half).toFixed(2), lat]);
	return dots;
}

/** the .js file the pages load */
function rleScript(world) {
	const rle = encodeRle(world);
	return `/* Generated by scripts/build-site.js from assets/data/world-dots.json. Do not edit. */\nwindow.FF_WORLD=${JSON.stringify(rle)};\n`;
}

/**
 * Static locator map for one story (post pages): an SVG window of the world centred on the story. No JavaScript, no
 * layout shift, works from file://. Dots close to the story are lit (accent), a wider ring is brighter.
 * @returns {{svg:string, pin:{x:number,y:number}, viewBox:string}}  pin is in percent of the box
 */
function locatorSvg(world, lat, lon, opts = {}) {
	const spanX = opts.spanX || 92, spanY = opts.spanY || 60;
	let cx = lon, cy = lat;
	cy = Math.max(-58 + spanY / 2, Math.min(82 - spanY / 2, cy));
	const x0 = cx - spanX / 2, y0 = -(cy + spanY / 2);
	const near = 8, hot = 3.2, cosL = Math.cos(lat * Math.PI / 180);
	const base = [], mid = [], lit = [];
	const rows = new Map();
	for (const [dx, dy] of world.dots) {
		for (const shift of [-360, 0, 360]) {
			const x = dx + shift;
			if (x < x0 - 2 || x > x0 + spanX + 2 || dy > -y0 + 2 || dy < -(y0 + spanY) - 2) continue;
			let dl = Math.abs(x - lon); const d = Math.sqrt((dl * cosL) ** 2 + (dy - lat) ** 2);
			const target = d < hot ? lit : d < near ? mid : base;
			target.push([x, dy]);
		}
	}
	const toPath = (pts) => {
		const byRow = new Map();
		for (const [x, y] of pts) { if (!byRow.has(y)) byRow.set(y, []); byRow.get(y).push(x); }
		let d = '';
		for (const y of [...byRow.keys()].sort((a, b) => b - a)) {
			const xs = byRow.get(y).sort((a, b) => a - b);
			xs.forEach((x, i) => { d += i === 0 ? `M${+x.toFixed(2)} ${+(-y).toFixed(2)}h0` : `m${+(x - xs[i - 1]).toFixed(2)} 0h0`; });
		}
		return d;
	};
	const w = spanX, h = spanY;
	const svg = `<svg class="loc__dots" viewBox="${+x0.toFixed(2)} ${+y0.toFixed(2)} ${w} ${h}" preserveAspectRatio="xMidYMid slice" aria-hidden="true" focusable="false">` +
		`<path class="d0" d="${toPath(base)}"/><path class="d1" d="${toPath(mid)}"/><path class="d2" d="${toPath(lit)}"/></svg>`;
	return { svg, pin: { x: +(((lon - x0) / w) * 100).toFixed(2), y: +(((-lat - y0) / h) * 100).toFixed(2) }, viewBox: `${x0} ${y0} ${w} ${h}` };
}

module.exports = { readDots, encodeRle, decodeRle, rleScript, locatorSvg };
