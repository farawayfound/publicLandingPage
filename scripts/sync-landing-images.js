#!/usr/bin/env node
/**
 * Regenerates Public_html/assets/images/Landing/landing-images.js
 * from files in that folder. Run: node scripts/sync-landing-images.js
 */
const fs   = require("fs");
const path = require("path");

const root    = path.join(__dirname, "..");
const dir     = path.join(root, "Public_html", "assets", "images", "Landing");
const allowed = new Set([".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif"]);

if (!fs.existsSync(dir)) {
	console.error("Landing folder not found:", dir);
	process.exit(1);
}

const images = fs
	.readdirSync(dir)
	.filter(name => allowed.has(path.extname(name).toLowerCase()))
	.sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }))
	.map(name => `  "assets/images/Landing/${name}"`)
	.join(",\n");

const content =
	`/* Auto-generated by scripts/sync-landing-images — do not edit manually */\n` +
	`window.LANDING_IMAGES = [\n${images}\n];\n`;

const out = path.join(dir, "landing-images.js");
fs.writeFileSync(out, content, "utf8");
const count = (content.match(/assets\/images/g) || []).length;
console.log(`Wrote ${count} paths to landing-images.js`);
