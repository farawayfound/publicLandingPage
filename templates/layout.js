/** A <script> reference with a content hash so a rebuilt asset is never served stale from a browser cache. */
function assetUrl(ctx, rel) {
	return `${ctx.prefix}${rel}${ctx.hash(rel) ? `?v=${ctx.hash(rel)}` : ''}`;
}

/** @param {object} o  { ctx, template, title, description, bodyClass, body, scripts, preload, og, canonical, ogType } */
function page(o) {
	const { ctx } = o;
	const { site } = ctx;
	const abs = (rel) => (ctx.siteUrl ? `${ctx.siteUrl}/${encPath(rel)}` : `${ctx.prefix}${encPath(rel)}`);
	const og = o.og || {};
	const canonical = ctx.siteUrl && o.pagePath ? `${ctx.siteUrl}/${o.pagePath}` : '';
	const desc = o.description || '';
	const head = [
		'<meta charset="utf-8">',
		'<meta name="viewport" content="width=device-width, initial-scale=1">',
		`<title>${esc(o.title)}</title>`,
		`<meta name="description" content="${esc(desc)}">`,
		`<meta name="theme-color" content="${esc(site.site.themeColor || '#0f051e')}">`,
		'<meta name="color-scheme" content="dark">',
		canonical ? `<link rel="canonical" href="${esc(canonical)}">` : '',
		`<meta property="og:site_name" content="${esc(site.site.name || 'FarawayFound')}">`,
		`<meta property="og:type" content="${o.ogType || 'website'}">`,
		`<meta property="og:title" content="${esc(o.ogTitle || o.title)}">`,
		`<meta property="og:description" content="${esc(desc)}">`,
		canonical ? `<meta property="og:url" content="${esc(canonical)}">` : '',
		og.image ? `<meta property="og:image" content="${esc(abs(og.image))}">` : '',
		og.image && og.w ? `<meta property="og:image:width" content="${og.w}">\n<meta property="og:image:height" content="${og.h}">` : '',
		og.image && og.alt ? `<meta property="og:image:alt" content="${esc(og.alt)}">` : '',
		`<meta name="twitter:card" content="${og.image ? 'summary_large_image' : 'summary'}">`,
		`<link rel="shortcut icon" href="${ctx.prefix}assets/favicon.ico">`,
		'<link rel="preconnect" href="https://fonts.googleapis.com">',
		'<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
		o.preload || '',
		`<link href="${FONTS}" rel="stylesheet">`,
		`<link rel="stylesheet" href="${assetUrl(ctx, 'assets/css/ff.css')}">`,
		"<script>document.documentElement.className=document.documentElement.className.replace('no-js','js')</script>",
	].filter(Boolean).join('\n');

	const scripts = (o.scripts || []).map((s) => (s.startsWith('<') ? s : `<script src="${assetUrl(ctx, s)}" defer></script>`)).join('\n');
	// failsafe: the .js class (set in <head>) hides scroll-reveal content until ff.js shows it. If ff.js never ran (blocked, failed to
	// download or parse) give the classic page back after a few seconds; ff.js turns .js back on when it does run late.
	const failsafe = "<script>setTimeout(function(){var h=document.documentElement;if(!(window.FF&&window.FF.ready)&&/(^|\\s)js(\\s|$)/.test(h.className))h.className=h.className.replace(/(^|\\s)js(\\s|$)/,' no-js ')},4500)</script>";
	return `<!-- GENERATED by scripts/build-site.js from templates/${o.template} and content/. Edit those files, not this page. -->
<!DOCTYPE html>
<html lang="${esc(site.site.lang || 'en')}" class="no-js" data-base="${esc(ctx.prefix)}">
<head>
${head}
</head>
<body class="${o.bodyClass}">
<a class="skip" href="#main">${esc(site.ui.skip)}</a>
${o.body}
${scripts}
${failsafe}
</body>
</html>
`;
}

/** The fixed top bar. links: [{href, label, external?}] */
function header(ctx, o) {
	const nav = o.links.map((l) => `<a href="${esc(l.href)}"${l.external ? ' target="_blank" rel="noopener noreferrer"' : ''}${l.sec ? ` data-sec="${l.sec}"` : ''}>${esc(l.label)}</a>`).join('\n    ');
	return `<header class="bar" id="top" data-header>
  <a class="bar__brand" href="${esc(o.brandHref)}" aria-label="${esc(ctx.site.site.name)}">${esc(ctx.site.site.name)}<span>.</span></a>
  ${o.menu ? `<button class="bar__toggle" type="button" aria-expanded="false" aria-controls="nav" aria-label="${esc(ctx.site.ui.menu)}"><i></i><i></i></button>` : ''}
  <nav class="bar__nav" id="nav" aria-label="Primary">
    ${nav}
  </nav>
</header>`;
}

/** Pause/play + n/N ticker used under every auto-advancing hero. `caption` is the story teaser (blog hero only). */
function ticker(ctx, o) {
	const pad = (n) => String(n).padStart(2, '0');
	return `<div class="ticker mono" data-ticker aria-label="Slideshow">
      ${o.caption || ''}
      <span class="ticks" data-ticks aria-hidden="true"></span>
      <button class="ticker__pause" type="button" aria-label="${esc(ctx.site.ui.pause)}" aria-pressed="false">${ICON.pausePlay}</button>
    </div>`;
}

/** Quiet footer used on every page. */
function footer(inner) {
	return `<footer class="foot">
  ${inner}
</footer>`;
}

/** The generated page-wide data scripts (FF_HERO etc.) */
function inlineJson(name, data) {
	return `<script>window.${name}=${jsonForScript(data)};</script>`;
}

module.exports = { page, header, ticker, footer, inlineJson, ICON, assetUrl };
