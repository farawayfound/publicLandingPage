# Regenerates Public_html/assets/images/Landing/landing-images.js (window.LANDING_IMAGES) from the files in the
# Landing folder. Run after adding or removing photos:
#   pwsh -File scripts/sync-landing-images.ps1
#
# The folder holds the 6000 px originals. Next to them, Landing/web/<name>.webp holds the optimised 2560 px
# versions. For every photo the list prefers web/<name>.webp when it exists and falls back to the original
# otherwise (a photo that only exists in web/ is listed too). Same rule as scripts/sync-landing-images.js.

$ErrorActionPreference = 'Stop'
$root   = Split-Path $PSScriptRoot -Parent
$dir    = Join-Path $root 'Public_html\assets\images\Landing'
$webDir = Join-Path $dir 'web'

if (-not (Test-Path $dir)) {
    Write-Error "Landing folder not found: $dir"
    exit 1
}

$ext = @('.jpg', '.jpeg', '.png', '.gif', '.webp', '.avif')

$originals = @{}
Get-ChildItem -LiteralPath $dir -File |
    Where-Object { $ext -contains $_.Extension.ToLower() } |
    ForEach-Object { $originals[$_.BaseName] = $_.Name }

$optimised = @{}
if (Test-Path $webDir) {
    Get-ChildItem -LiteralPath $webDir -File |
        Where-Object { $_.Extension.ToLower() -eq '.webp' } |
        ForEach-Object { $optimised[$_.BaseName] = $_.Name }
}

$stems = @($originals.Keys) + @($optimised.Keys) | Sort-Object -Unique

$lines = @($stems | ForEach-Object {
    if ($optimised.ContainsKey($_)) { "  `"assets/images/Landing/web/$($optimised[$_])`"" }
    else                            { "  `"assets/images/Landing/$($originals[$_])`"" }
})

$content = @"
/* Auto-generated by scripts/sync-landing-images -- do not edit manually */
window.LANDING_IMAGES = [
$($lines -join ",`n")
];
"@

$out = Join-Path $dir 'landing-images.js'
Set-Content -LiteralPath $out -Value $content -Encoding utf8
Write-Host "Wrote $($stems.Count) paths to landing-images.js"
