#!/usr/bin/env node
/**
 * Regenerates Public_html/assets/images/Landing/landing-images.js (window.LANDING_IMAGES) from the files in the
 * Landing folder. Run: node scripts/sync-landing-images.js
 *
 * The folder holds the 6000 px originals (8 MB each). Next to them, Landing/web/<name>.webp holds the optimised
 * 2560 px versions. For every photo this list prefers web/<name>.webp when it exists and falls back to the original
 * otherwise. A photo that only exists in web/ is listed too.
 *
 * scripts/build-site.js uses collectLandingImages() from this file, so the landing page slideshow and
 * landing-images.js always agree.
 */
const fs   = require("fs");
const path = require("path");

const allowed = new Set([".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif"]);
const byName  = (a, b) => a.localeCompare(b, undefined, { sensitivity: "base" });

/** @returns {string[]} site-relative paths such as "assets/images/Landing/web/DSC_0768.webp" */
function collectLandingImages(publicRoot) {
	const dir    = path.join(publicRoot, "assets", "images", "Landing");
	const webDir = path.join(dir, "web");
	if (!fs.existsSync(dir)) throw new Error("Landing folder not found: " + dir);

	const list = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }) : [])
		.filter(e => e.isFile() && allowed.has(path.extname(e.name).toLowerCase()))
		.map(e => e.name);

	const stem = (n) => n.slice(0, n.length - path.extname(n).length);
	const originals = new Map(list(dir).map(n => [stem(n), n]));
	const optimised = new Map(list(webDir).filter(n => path.extname(n).toLowerCase() === ".webp").map(n => [stem(n), n]));

	const names = [...new Set([...originals.keys(), ...optimised.keys()])].sort(byName);
	return names.map(s => optimised.has(s)
		? `assets/images/Landing/web/${optimised.get(s)}`
		: `assets/images/Landing/${originals.get(s)}`);
}

function writeLandingImagesJs(publicRoot) {
	const images = collectLandingImages(publicRoot).map(p => `  "${p}"`).join(",\n");
	const content =
		`/* Auto-generated by scripts/sync-landing-images — do not edit manually */\n` +
		`window.LANDING_IMAGES = [\n${images}\n];\n`;
	const out = path.join(publicRoot, "assets", "images", "Landing", "landing-images.js");
	let prev = null;
	try { prev = fs.readFileSync(out, "utf8"); } catch (e) { /* first run */ }
	if (prev !== content) fs.writeFileSync(out, content, "utf8");
	return { out, count: (content.match(/assets\/images/g) || []).length };
}

module.exports = { collectLandingImages, writeLandingImagesJs };

if (require.main === module) {
	try {
		const { count } = writeLandingImagesJs(path.join(__dirname, "..", "Public_html"));
		console.log(`Wrote ${count} paths to landing-images.js`);
	} catch (e) {
		console.error(e.message);
		process.exit(1);
	}
}
